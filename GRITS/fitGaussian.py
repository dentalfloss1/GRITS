from distutils.version import LooseVersion
import warnings
import numpy as np
import scipy
from scipy import optimize

# Written by Jake Hartman for PASI
# The handling of warning messages from scipy.optimize routines changed
# between versions.  For v0.7 and earlier, functions took a warnings keyword
# arg to control warning verbosity.  For v0.8 and later, the warnings module
# is used.

if LooseVersion(scipy.__version__) < LooseVersion('0.8'):
    optimizeExtraArgs = {'warning': False}
else:
    optimizeExtraArgs = {}


def gaussian(params, x, y):
    level, dleveldx, dleveldy, height, x0, y0, rad = params
    return level + dleveldx * x + dleveldy * y + \
        height * np.exp(-((x - x0)**2 + (y - y0)**2) / (2 * rad**2))


def fitGaussian(data, dataCoords, params,
                freeze = None,
                maxOffset = None):
    """
    Returns a tuple of the gaussian parameters of a 2D distribution found by a
    fit: (level, dleveldx, dleveldy, height, x0, y0, rad).  If the fit fails,
    returns None.
    """
    x, y = dataCoords
    params = np.array(params, dtype = float)
    
    if freeze is None:
        return fitGaussian_freezeNone(
            data, dataCoords, params, maxOffset = maxOffset)
    elif freeze == [0]:
        return fitGaussian_freezeLevel(
            data, dataCoords, params, maxOffset = maxOffset)
    else:
        fitFlags = np.ones(len(params), bool)
        fitFlags[np.array(freeze)] = False
        iFitParams = fitFlags.nonzero()[0]
    
    initx0, inity0 = params[4:6]
    if maxOffset is None:
        maxOffset, penaltyFactor = 1e9, 0
    else:
        penaltyFactor = data.max() * 10
    
    def residFunc(p):
        params[iFitParams] = p
        level, dleveldx, dleveldy, height, x0, y0, rad = params
        gaussian = \
            level + dleveldx * x + dleveldy * y + \
            height * np.exp(-((x - x0)**2 + (y - y0)**2) / (2 * rad**2))
        offsetPenalty = penaltyFactor * max(
            0, np.hypot(x0 - initx0, y0 - inity0) - maxOffset)
        return np.r_[gaussian - data, offsetPenalty]
    
    def jacobian(p):
        params[iFitParams] = p
        level, dleveldx, dleveldy, height, x0, y0, rad = params
        offset2 = (x - x0)**2 + (y - y0)**2
        expTerm = np.exp(-offset2 / (2 * rad**2))
        offset = np.hypot(x0 - initx0, y0 - inity0)
        offsetPenalty = penaltyFactor / offset if offset > maxOffset else 0.
        jac = np.zeros((len(p), len(data) + 1))
        for i, iFP in enumerate(iFitParams):
            if iFP == 0:
                jac[i, :-1] = np.ones(len(x))
            elif iFP == 1:
                jac[i, :-1] = x
            elif iFP == 2:
                jac[i, :-1] = y
            elif iFP == 3:
                jac[i, :-1] = expTerm
            elif iFP == 4:
                jac[i, :-1] = height * (x - x0) / rad**2 * expTerm
                jac[i, -1] = (x0 - initx0) * offsetPenalty
            elif iFP == 5:
                jac[i, :-1] = height * (y - y0) / rad**2 * expTerm
                jac[i, -1] = (y0 - inity0) * offsetPenalty
            elif iFP == 6:
                jac[i, :-1] = height * offset2 / rad**3 * expTerm
        return jac
    
    with warnings.catch_warnings():
        # Do not print runtime warnings generated by leastsq() to stderr.
        warnings.simplefilter('ignore', RuntimeWarning)
        params[iFitParams], success = optimize.leastsq(
            residFunc, params[iFitParams], Dfun = jacobian, col_deriv = True,
            maxfev = 100, xtol = 1e-4, **optimizeExtraArgs)
    
    if success > 0 and success <= 4 and np.prod(np.isfinite(params)):
        return params
    else:
        return None


def fitGaussian_freezeNone(data, dataCoords, params,
                           maxOffset = None):
    """
    Special case of fitGaussian() with no parameters frozen.
    """
    x, y = dataCoords
    params = np.array(params, dtype = float)
    
    initx0, inity0 = params[4:6]
    if maxOffset is None:
        maxOffset, penaltyFactor = 1e9, 0
    else:
        penaltyFactor = data.max() * 10
    
    def residFunc(params):
        level, dleveldx, dleveldy, height, x0, y0, rad = params
        gaussian = \
            level + dleveldx * x + dleveldy * y + \
            height * np.exp(-((x - x0)**2 + (y - y0)**2) / (2 * rad**2))
        offsetPenalty = penaltyFactor * max(
            0, np.hypot(x0 - initx0, y0 - inity0) - maxOffset)
        return np.r_[gaussian - data, offsetPenalty]
    
    def jacobian(params):
        level, dleveldx, dleveldy, height, x0, y0, rad = params
        offset2 = (x - x0)**2 + (y - y0)**2
        expTerm = np.exp(-offset2 / (2 * rad**2))
        offset = np.hypot(x0 - initx0, y0 - inity0)
        offsetPenalty = penaltyFactor / offset if offset > maxOffset else 0.
        jac = np.empty((7, len(data) + 1))
        jac[:, :-1] = [
            np.ones(len(x)), x, y, expTerm,
            height * (x - x0) / rad**2 * expTerm,
            height * (y - y0) / rad**2 * expTerm,
            height * offset2 / rad**3 * expTerm]
        jac[:, -1] = [
            0., 0., 0., 0.,
            (x0 - initx0) * offsetPenalty, (y0 - inity0) * offsetPenalty, 0.]
        return jac
    
    with warnings.catch_warnings():
        # Do not print runtime warnings generated by leastsq() to stderr.
        warnings.simplefilter('ignore', RuntimeWarning)
        params, success = optimize.leastsq(
            residFunc, params, Dfun = jacobian, col_deriv = True,
            maxfev = 100, xtol = 1e-4, **optimizeExtraArgs)
    
    if success > 0 and success <= 4 and np.prod(np.isfinite(params)):
        return params
    else:
        return None


def fitGaussian_freezeLevel(data, dataCoords, params,
                            maxOffset = None):
    """
    Special case of fitGaussian() with the constant offset level frozen.
    """
    x, y = dataCoords
    params = np.array(params, dtype = float)
    
    initx0, inity0 = params[4:6]
    if maxOffset is None:
        maxOffset, penaltyFactor = 1e9, 0
    else:
        penaltyFactor = data.max() * 10
    
    def residFunc(p):
        level = params[0]
        dleveldx, dleveldy, height, x0, y0, rad = p
        gaussian = \
            level + dleveldx * x + dleveldy * y + \
            height * np.exp(-((x - x0)**2 + (y - y0)**2) / (2 * rad**2))
        offsetPenalty = penaltyFactor * max(
            0, np.hypot(x0 - initx0, y0 - inity0) - maxOffset)
        return np.r_[gaussian - data, offsetPenalty]
    
    def jacobian(p):
        level = params[0]
        dleveldx, dleveldy, height, x0, y0, rad = p
        offset2 = (x - x0)**2 + (y - y0)**2
        expTerm = np.exp(-offset2 / (2 * rad**2))
        offset = np.hypot(x0 - initx0, y0 - inity0)
        offsetPenalty = penaltyFactor / offset if offset > maxOffset else 0.
        jac = np.empty((6, len(data) + 1))
        jac[:, :-1] = [
            x, y, expTerm,
            height * (x - x0) / rad**2 * expTerm,
            height * (y - y0) / rad**2 * expTerm,
            height * offset2 / rad**3 * expTerm]
        jac[:, -1] = [
            0., 0., 0.,
            (x0 - initx0) * offsetPenalty, (y0 - inity0) * offsetPenalty, 0.]
        return jac
    
    with warnings.catch_warnings():
        # Do not print runtime warnings generated by leastsq() to stderr.
        warnings.simplefilter('ignore', RuntimeWarning)
        params[1:], success = optimize.leastsq(
            residFunc, params[1:], Dfun = jacobian, col_deriv = True,
            maxfev = 100, xtol = 1e-4, **optimizeExtraArgs)
    
    if success > 0 and success <= 4 and np.prod(np.isfinite(params)):
        return params
    else:
        return None
